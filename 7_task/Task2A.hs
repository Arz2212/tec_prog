-- Задача 2А: Бесконечный список всех двумерных точек
-- с целочисленными координатами.
-- Точки перебираются «квадратами» по возрастанию max(|x|,|y|).

module Task2A where

-- Генерируем все точки (x,y) ∈ ℤ²:
--   k=0: (0,0)
--   k=1: периметр квадрата [-1,1]×[-1,1] (8 точек)
--   k=2: периметр квадрата [-2,2]×[-2,2] (16 точек)
--   и т.д.
-- Каждая точка встречается ровно один раз.

allPoints :: [(Integer, Integer)]
allPoints = (0,0) : [ (x,y) | k <- [1..], (x,y) <- ring k ]
  where
    ring k = [ (k, y)  | y <- [-k..k] ]       -- правая грань
          ++ [ (-k, y) | y <- [-k..k] ]       -- левая грань
          ++ [ (x, k)  | x <- [-(k-1)..(k-1)] ]  -- верхняя грань (без углов)
          ++ [ (x, -k) | x <- [-(k-1)..(k-1)] ]  -- нижняя грань (без углов)
