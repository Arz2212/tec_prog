
% Пустой список
remove_third([], []).

% Список из одного элемента
remove_third([X], [X]).

% Список из двух элементов
remove_third([X, Y], [X, Y]).

% Список из трёх и более элементов:
% первые два сохраняем, третий отбрасываем, рекурсивно обрабатываем хвост
remove_third([X, Y, _ | Tail], [X, Y | Result]) :-
    remove_third(Tail, Result).
