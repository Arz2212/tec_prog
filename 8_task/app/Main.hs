-- |
-- Module      : Main
-- Description : Демонстрация дерева квадрантов в контексте муравьиной симуляции.
--
-- Показывает: создание quadtree для карты 800×800, вставку агентов и еды,
-- поиск соседей в радиусе взаимодействия, монадическую цепочку операций,
-- и красивый вывод дерева в консоль (Show).
--
module Main where

import QuadTree

-- ---------------------------------------------------------------------------
-- ТИПЫ ДАННЫХ ДЛЯ ДЕМОНСТРАЦИИ (аналогично C++ проекту)
-- ---------------------------------------------------------------------------

-- | Тип агента
data AgentType = Scout | Worker deriving (Show, Eq)

-- | Данные, которые хранятся в точке quadtree
data Entity = Entity
  { entityType :: String      -- "agent" или "food"
  , agentRole  :: Maybe AgentType
  , energy     :: Int
  , entityId   :: String
  } deriving (Show, Eq)

-- | Создать агента
mkAgent :: String -> AgentType -> Int -> Entity
mkAgent eid role en = Entity "agent" (Just role) en eid

-- | Создать еду
mkFood :: String -> Int -> Entity
mkFood fid en = Entity "food" Nothing en fid

-- ---------------------------------------------------------------------------
-- ДЕМОНСТРАЦИЯ
-- ---------------------------------------------------------------------------

main :: IO ()
main = do
  putStrLn "╔══════════════════════════════════════════════════════════╗"
  putStrLn "║   ДЕМОНСТРАЦИЯ: Дерево квадрантов (Quadtree)            ║"
  putStrLn "║   Муравьиная колония — хранение агентов и еды           ║"
  putStrLn "╚══════════════════════════════════════════════════════════╝"

  -- Карта 800×800, центр (400,400), полуразмер 400
  let mapR = Region 400.0 400.0 400.0

  -- -----------------------------------------------------------------------
  -- 1. Создание пустого дерева и вставка сущностей
  -- -----------------------------------------------------------------------
  putStrLn "\n─── 1. Создание дерева и вставка сущностей ───"

  let tree0 = empty mapR

  -- Вставляем базу в центре
  let tree1 = insert (Point 400.0 400.0 (mkAgent "base1" Worker 1000)) tree0

  -- Вставляем рабочих
  let tree2 = insert (Point 200.0 300.0 (mkAgent "w1" Worker 100)) tree1
  let tree3 = insert (Point 250.0 350.0 (mkAgent "w2" Worker 100)) tree2
  let tree4 = insert (Point 500.0 200.0 (mkAgent "w3" Worker 80)) tree3

  -- Вставляем разведчиков
  let tree5 = insert (Point 600.0 500.0 (mkAgent "s1" Scout 120)) tree4
  let tree6 = insert (Point 100.0 100.0 (mkAgent "s2" Scout 150)) tree5
  let tree7 = insert (Point 700.0 700.0 (mkAgent "s3" Scout 90)) tree6

  -- Вставляем источники еды
  let tree8 = insert (Point 150.0 400.0 (mkFood "f1" 500)) tree7
  let tree9 = insert (Point 650.0 350.0 (mkFood "f2" 300)) tree8
  let tree0' = insert (Point 300.0 600.0 (mkFood "f3" 200)) tree9

  putStrLn $ "  Всего сущностей в дереве: " ++ show (size tree0')

  -- -----------------------------------------------------------------------
  -- 2. Поиск в радиусе (главная операция симуляции)
  -- -----------------------------------------------------------------------
  putStrLn "\n─── 2. Поиск соседей в радиусе (агент-агент взаимодействие) ───"

  -- Рабочий w1 на позиции (200,300) ищет соседей в радиусе 80
  let neighborsOfW1 = queryRadius tree0' 200 300 80
  putStrLn "  Соседи рабочего w1 (200,300) в радиусе 80:"
  mapM_ (putStrLn . ("    → " ++) . show) neighborsOfW1

  -- Разведчик s3 на позиции (700,700) в радиусе 100
  let neighborsOfS3 = queryRadius tree0' 700 700 100
  putStrLn "  Соседи разведчика s3 (700,700) в радиусе 100:"
  mapM_ (putStrLn . ("    → " ++) . show) neighborsOfS3

  -- -----------------------------------------------------------------------
  -- 3. Поиск в прямоугольной области
  -- -----------------------------------------------------------------------
  putStrLn "\n─── 3. Поиск в прямоугольной области ───"

  -- Все сущности в левом верхнем квадранте
  let leftTop = Region 200 200 200
  let inQuadrant = queryRegion tree0' leftTop
  putStrLn "  Сущности в левом верхнем квадранте (0..400, 0..400):"
  mapM_ (putStrLn . ("    → " ++) . show) inQuadrant

  -- -----------------------------------------------------------------------
  -- 4. Монадическая цепочка операций
  -- -----------------------------------------------------------------------
  putStrLn "\n─── 4. Монадическая цепочка операций ───"

  let (result, finalTree) = runQTreeM (empty mapR) $ do
        -- Вставляем несколько сущностей
        insertM (Point 100 100 (mkAgent "a1" Worker 100))
        insertM (Point 120 120 (mkAgent "a2" Scout 100))
        insertM (Point 500 500 (mkFood "food1" 200))
        insertM (Point 130 110 (mkAgent "a3" Worker 80))

        -- Ищем соседей вокруг (100,100)
        neighbors <- queryRadiusM 100 100 50
        sz <- sizeM
        pure (neighbors, sz)

  let (nbrs, sz) = result
  putStrLn $ "  Вставлено сущностей: " ++ show sz
  putStrLn $ "  Соседей вокруг (100,100) в радиусе 50: " ++ show (length nbrs)
  putStrLn $ "  Итоговый размер дерева: " ++ show (size finalTree)

  -- -----------------------------------------------------------------------
  -- 5. Красивый вывод дерева (Show)
  -- -----------------------------------------------------------------------
  putStrLn "\n─── 5. Вывод дерева в консоль (Show) ───"
  putStrLn "\n"  -- отступ перед выводом
  putStrLn "  Содержимое дерева квадрантов (все 11 сущностей):"
  putStrLn ""

  -- Выводим всё дерево (может быть большим, но для 11 элементов — нормально)
  putStrLn $ show tree0'

  -- -----------------------------------------------------------------------
  -- 6. Сводка
  -- -----------------------------------------------------------------------
  putStrLn "\n─── 6. Сводка ───"
  putStrLn $ "  Размер дерева:               " ++ show (size tree0')
  putStrLn $ "  Всех точек (toList):         " ++ show (length (toList tree0'))
  putStrLn $ "  Ёмкость листа (capacity):    " ++ show capacity
  putStrLn $ "  Карта:                       800×800"
  putStrLn "\n  ✅ Демонстрация завершена."
